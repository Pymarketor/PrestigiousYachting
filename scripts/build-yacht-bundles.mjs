import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const bundles = {
  "yacht-template-critical.bundle.js": [
    "yacht-template-head.js",
    "py-yacht-video-safe-v2.js",
    "yacht-gallery-mobile-scroll-focus.js"
  ],
  "yacht-template-runtime.bundle.js": [
    "yacht-template-footer.js",
    "yacht-spec-icons-svg.js",
    "yacht-feature-icons.js",
    "yacht-mobile-info-fix.js",
    "yacht-info-stack-fix.js",
    "py-apple-reveal.js",
    "yacht-mobile-input-fix.js",
    "similarsectionv1.js"
  ]
};

for (const [target, sources] of Object.entries(bundles)) {
  const kind = target.includes("critical") ? "critical" : "deferred";
  const header = `/* Prestigious Yachting — ${kind} CMS yacht template bundle\n * Generated by scripts/build-yacht-bundles.mjs. Edit source modules, then rebuild.\n */`;
  const modules = await Promise.all(sources.map(async (source) => {
    const content = (await readFile(resolve(root, source), "utf8")).trim();
    return `/* ===== ${source} ===== */\n${content}`;
  }));
  await writeFile(resolve(root, target), `${header}\n\n${modules.join("\n\n;\n\n")}\n`, "utf8");
}
